import ast
from py2ver.visitor import FunctionVisitor
from py2ver.renderer import Renderer
from py2ver import DEFAULT_TEMPLATE_DIR

def unit_render_add_xor(a, b):
    x = (a & 0xF) + (b & 0xF)
    y = (a ^ b) << 1
    return x, y


def test_renderer_smoke(tmp_path, toy_src_add_xor, attr_simple):
    ir = FunctionVisitor(attr_simple).visit(ast.parse(toy_src_add_xor))

    r = Renderer(DEFAULT_TEMPLATE_DIR)
    verilog = r.render_module(ir)

    assert "module foo" in verilog
    assert "a" in verilog and "b" in verilog and "x" in verilog and "y" in verilog
    assert "output" in verilog
    assert ("assign x =" in verilog) or ("x <=" in verilog)
    assert ("assign y =" in verilog) or ("y <=" in verilog)

    (tmp_path / "foo.v").write_text(verilog)


def test_renderer_smoke_py_vs_sim(attr_simple, assert_python_matches_sim):
    assert_python_matches_sim(unit_render_add_xor, attr_simple, [(2, 3), (4, 9), (15, 15)])


def _mac(acc, x, k):
    p = x * k
    return acc + p


_TAPS = [3, -5, 7]


def commented_fir(x, d0, d1):
    window = [x, d0, d1]
    acc = 0
    for k in range(3):
        acc = _mac(acc, window[k],
                   _TAPS[k])
    return acc


def test_comments_quote_the_python_lines(monkeypatch, tmp_path):
    import inspect
    from py2ver import Py2ver
    monkeypatch.chdir(tmp_path)
    Py2ver(commented_fir, {n: {"signed": 1, "width": 8} for n in ("x", "d0", "d1")})
    verilog = (tmp_path / "hdl" / "main.v").read_text()
    first = inspect.getsourcelines(commented_fir)[1]
    assert f"// Generated by py2ver from commented_fir() (test_render_module.py, line {first})" \
        in verilog
    lines = verilog.splitlines()
    call = lines.index(f"// line {first + 4}: acc = _mac(acc, window[k], _TAPS[k])")
    # the helper's code, all three calls of it, under its call
    body = lines[call + 1:lines.index("", call)]
    assert sum("__mac" in line and "_p" in line.split("=")[0] for line in body) == 3
    assert f"// line {first + 2}: acc = 0" in lines
